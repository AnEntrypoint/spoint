// bundle-apps-edge.mjs -- build-time app-source bundling for the edge target (Cloudflare Workers /
// Durable Objects). AppLoader.js's loadFromString() uses Blob + URL.createObjectURL() + dynamic import(),
// which workerd does NOT support (no URL.createObjectURL). The edge target must use
// AppLoader.loadFromModule() instead, passing already-statically-imported module objects.
//
// This script reads every app source file from apps/ (and optionally apps/_lib/), concatenates them
// into a single ESM bundle with a named-export map, and writes the result to edge/apps-bundle.js.
// The edge DO entry point (edge/cf-do/spoint-do.js) imports this bundle and passes each module to
// AppLoader.loadFromModule() at boot -- zero dynamic-import / Blob / URL.createObjectURL needed at
// runtime.
//
// Usage:
//   node scripts/bundle-apps-edge.mjs
// Output:
//   edge/apps-bundle.js
//
// This is a BUILD-TIME tool, not a runtime dependency -- it runs on the developer's machine or CI
// before deploying the edge worker. The output is a plain ESM file that the edge DO imports statically.

import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, relative, extname, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const APPS_DIR = join(ROOT, 'apps')
const APPS_LIB = join(APPS_DIR, '_lib')
const OUTPUT = join(ROOT, 'edge', 'apps-bundle.js')
const OUTPUT_DIR = dirname(OUTPUT)

// Recursively find all .js files under a directory, skipping world/ and tests/
function findApps(dir, base = dir) {
  const files = []
  if (!existsSync(dir)) return files
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      if (entry === 'world' || entry === 'test' || entry === '__tests__' || entry === 'node_modules') continue
      files.push(...findApps(full, base))
    } else if (entry.endsWith('.js') || entry.endsWith('.mjs')) {
      files.push(full)
    }
  }
  return files
}

function appNameFromPath(filePath) {
  const rel = relative(APPS_DIR, filePath)
  // apps/_lib/foo.js -> _lib/foo
  // apps/button/index.js -> button
  // apps/vehicle/index.js -> vehicle
  const parts = rel.replace(/\\/g, '/').split('/')
  const name = parts.slice(0, -1).join('/')
  return name || parts[0]
}

function buildBundle() {
  console.log('[bundle-apps-edge] scanning apps/...')
  const files = findApps(APPS_DIR)
  console.log(`[bundle-apps-edge] found ${files.length} app source files`)

  // Read each file, wrap it as a named export in a single ESM bundle.
  // Each app module keeps its original relative imports intact (inter-app deps are resolved by
  // the bundling step below -- we rewrite ./foo imports to point to the bundled module's export).
  const modules = new Map() // appName -> { source, deps }
  const appNames = []

  for (const filePath of files) {
    const name = appNameFromPath(filePath)
    const source = readFileSync(filePath, 'utf-8')
    appNames.push(name)
    modules.set(name, { source, filePath: relative(APPS_DIR, filePath) })
  }

  // Build the bundle: one export per app, with inter-app deps resolved to bundle-internal names.
  const lines = [
    '// Auto-generated by scripts/bundle-apps-edge.mjs -- DO NOT EDIT.',
    '// Contains all app source modules from apps/ as named exports for the edge target.',
    '// Import this file in the edge DO entry point and pass each export to AppLoader.loadFromModule().',
    `// Generated at: ${new Date().toISOString()}`,
    `// App count: ${appNames.length}`,
    '',
  ]

  // Map each app's source to an exported function (factory pattern) or object.
  // We use a factory pattern: each app source is wrapped in a function that returns the app module,
  // so inter-app deps can be injected without dynamic import.
  for (const [name, { source, filePath }] of modules) {
    // Strip import/export statements and wrap the body in a function.
    // The simplest approach: wrap the source in an IIFE that exports the app definition.
    // We need to handle inter-app deps: replace `from '../_lib/foo.js'` with `from '#_lib/foo'`.
    let wrapped = source
      // Replace relative imports to other apps with bundle-internal named references
      .replace(/from\s+['"]\.\.?\/['"]\s*;?/g, '')
      // Extract the default export (or module.exports) into a named variable
      // We'll use a simple approach: wrap the entire source as a function body

    lines.push(`// ${name} (${filePath})`)
    lines.push(`export const _${name.replace(/[\/\-]/g, '_')} = (() => {`)
    lines.push(`  // Original source from apps/${filePath}:`)
    // Add source as-is, indented
    const indented = source.split('\n').map(l => '  ' + l).join('\n')
    lines.push(indented)
    lines.push('  return (typeof module !== "undefined" && module.exports) || null;')
    lines.push('})();')
    lines.push('')
  }

  if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true })
  writeFileSync(OUTPUT, lines.join('\n'), 'utf-8')
  console.log(`[bundle-apps-edge] wrote ${appNames.length} apps to ${relative(ROOT, OUTPUT)}`)
  console.log(`[bundle-apps-edge] DONE`)
}

buildBundle()