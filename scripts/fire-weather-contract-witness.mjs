import { pathToFileURL, fileURLToPath } from 'node:url';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const checks = [];
const check = (name, ok, detail = '') => { checks.push({ name, ok }); console.log(`check ${name}: ${ok ? 'ok' : 'FAIL'}${detail ? ` (${detail})` : ''}`) };
const { createFireWeather } = await import(pathToFileURL(path.join(ROOT, 'src/behaviours/fireWeather.js')).href);
const { DEFAULT_FIRE_WEATHER } = await import(pathToFileURL(path.join(ROOT, 'src/behaviours/fireSpec.js')).href);
const STEP = 30;
const weatherAfterOneStep = (value) => {
  const f = createFireWeather({ config: DEFAULT_FIRE_WEATHER, readWeather: () => value, stepTicks: STEP });
  f.step(0, {});
  return f;
};
const absent = weatherAfterOneStep(undefined);
check('absent weather reads as no-weather with zero rain', absent.reading.kind === 'no-weather' && absent.rain === 0, `kind=${absent.reading.kind} rain=${absent.rain}`);
const junk = weatherAfterOneStep('nope');
check('a non-object weather reads as unreadable-weather with zero rain', junk.reading.kind === 'unreadable-weather' && junk.rain === 0, `kind=${junk.reading.kind}`);
const nanIntensity = weatherAfterOneStep({ type: 'rain', intensity: NaN });
check('a non-finite intensity reads as unreadable-weather with zero rain', nanIntensity.reading.kind === 'unreadable-weather' && nanIntensity.rain === 0, `kind=${nanIntensity.reading.kind}`);
const fog = weatherAfterOneStep({ type: 'fog', intensity: 1 });
check('a type other than rain or snow is dry-other with zero rain', fog.reading.kind === 'dry-other' && fog.rain === 0, `kind=${fog.reading.kind} rain=${fog.rain}`);
const rain = weatherAfterOneStep({ type: 'rain', intensity: 1 });
check('full rain is kind rain with rain byte 255', rain.reading.kind === 'rain' && rain.rain === 255, `rain=${rain.rain}`);
const snow = weatherAfterOneStep({ type: 'snow', intensity: 1 });
check('full snow is kind snow with rain byte 64 (255 x 0.25, rounded)', snow.reading.kind === 'snow' && snow.rain === 64, `rain=${snow.rain}`);
const over = weatherAfterOneStep({ type: 'rain', intensity: 3 });
check('intensity is clamped to 1', over.reading.intensity === 1 && over.rain === 255, `intensity=${over.reading.intensity}`);
const gusty = weatherAfterOneStep({ type: 'rain', intensity: 0.5, wind: [40, -40, 3.4] });
check('wind is clamped to the fire wind bound and rounded', gusty.wind[0] === 16 && gusty.wind[1] === -16 && gusty.wind[2] === 3, `wind=${JSON.stringify(gusty.wind)}`);
let current = { type: 'rain', intensity: 1 };
const wet = createFireWeather({ config: DEFAULT_FIRE_WEATHER, readWeather: () => current, stepTicks: STEP });
for (let t = 0; t < 3; t++) wet.step(t * STEP, {});
const wetMoisture = wet.moisture;
check('moisture rises under rain by wetPerStep per step', wetMoisture === 3 * DEFAULT_FIRE_WEATHER.wetPerStep, `moisture=${wetMoisture}`);
current = { type: 'fog', intensity: 0 };
wet.step(3 * STEP, {});
wet.step(4 * STEP, {});
check('moisture dries by exactly dryPerStep per dry step', wet.moisture === wetMoisture - 2 * DEFAULT_FIRE_WEATHER.dryPerStep, `before=${wetMoisture} after=${wet.moisture}`);
const off = createFireWeather({ config: DEFAULT_FIRE_WEATHER, readWeather: () => ({ type: 'rain', intensity: 1 }), stepTicks: STEP });
check('an off-step tick does not advance the weather', off.step(7, {}) === null && off.reading.kind === 'no-weather');
const failed = checks.filter((c) => !c.ok);
console.log(failed.length === 0 ? 'RESULT: PASS fire weather parses the documented kinds and bounds' : `RESULT: FAIL ${failed.length} check(s): ${failed.map((c) => c.name).join('; ')}`);
process.exitCode = failed.length === 0 ? 0 : 1;
