import assert from 'node:assert/strict'
import { definePath } from '../src/behaviours/path.js'

const EPS = 1e-9
const P0 = [0, 0, 0], P1 = [10, 0, 0], P2 = [10, 0, 10]
const PTS = [P0, P1, P2]
const RETURN_LEN = Math.hypot(10, 0, 10)

const approx = (a, b, msg) => assert.ok(Math.abs(a - b) <= EPS, `${msg}: ${a} vs ${b}`)
const arrEq = (a, b, msg) => assert.ok(a.length === b.length && a.every((v, i) => Math.abs(v - b[i]) <= EPS), `${msg}: ${JSON.stringify(a)} vs ${JSON.stringify(b)}`)
let refusals = 0
const refuses = (fn, code) => { refusals++; assert.throws(fn, e => e && e.reasonCode === code, `expected refusal code ${code}`) }

const MEMBERS = ['count', 'directionAt', 'length', 'nearestIndex', 'onChartReanchor', 'pointAt', 'progressAt', 'segmentAt', 'closed', 'distance', 'nearest', 'at']

const open = definePath(PTS)
for (const k of MEMBERS) assert.ok(k in open, `handle missing ${k}`)
assert.equal(open.closed, false)
assert.equal(open.count, 3)
approx(open.length, 20, 'open length')
assert.equal(typeof open.onChartReanchor, 'function')
arrEq(open.at(0), P0, 'open at(0)')
arrEq(open.at(1), P1, 'open at(1)')
arrEq(open.at(2), P2, 'open at(2)')
arrEq(open.at(-5), P0, 'open at(-5) clamps low')
arrEq(open.at(99), P2, 'open at(99) clamps high')
const atCopy = open.at(1); atCopy[0] = 999
arrEq(open.at(1), P1, 'at returns a fresh copy')
arrEq(open.pointAt(5), [5, 0, 0], 'open pointAt(5)')
arrEq(open.pointAt(15), [10, 0, 5], 'open pointAt(15)')
arrEq(open.directionAt(0), [1, 0, 0], 'open directionAt(0)')
arrEq(open.directionAt(15), [0, 0, 1], 'open directionAt(15)')
assert.equal(open.nearestIndex([10, 0, 10]), 2)
approx(open.progressAt([5, 0, 0]), 0.25, 'open progressAt')
assert.equal(open.segmentAt(5).index, 0)
approx(open.segmentAt(5).t, 0.5, 'open segmentAt(5) t')

approx(open.distance(5, 3), 3, 'open distance(5,3) no cutoff')
approx(open.distance(5, 3, Infinity), 3, 'open distance within Infinity')
approx(open.distance(5, 3, 4), 3, 'open distance within 4')
approx(open.distance(5, 3, 3), 3, 'open distance within 3 inclusive')
assert.equal(open.distance(5, 3, 2), Infinity, 'open distance beyond within 2')
const on = open.nearest(5, 3)
assert.deepEqual(Object.keys(on).sort(), ['distance', 'index', 'point', 't'])
assert.equal(on.index, 0)
approx(on.t, 0.5, 'open nearest(5,3) t')
arrEq(on.point, [5, 0, 0], 'open nearest(5,3) point')
approx(on.distance, 3, 'open nearest(5,3) distance')
assert.ok(open.nearest(5, 3, 4) !== null, 'open nearest within 4')
assert.equal(open.nearest(5, 3, 2), null, 'open nearest beyond within 2')
approx(open.distance(7, 7), 3, 'open distance(7,7) has no return segment')

const closed = definePath(PTS, { closed: true })
for (const k of MEMBERS) assert.ok(k in closed, `closed handle missing ${k}`)
assert.equal(closed.closed, true)
assert.equal(closed.count, 3)
approx(closed.length, 20 + RETURN_LEN, 'closed length includes return segment')
arrEq(closed.at(3), P0, 'closed at(3) wraps to 0')
arrEq(closed.at(4), P1, 'closed at(4) wraps to 1')
arrEq(closed.at(-1), P2, 'closed at(-1) wraps to 2')
arrEq(closed.at(6), P0, 'closed at(6) wraps to 0')
arrEq(closed.pointAt(closed.length), P0, 'closed pointAt(length) returns to start')
arrEq(closed.directionAt(closed.length), [-1 / Math.SQRT2, 0, -1 / Math.SQRT2], 'closed return direction')
assert.equal(closed.segmentAt(closed.length).index, 2)
approx(closed.segmentAt(closed.length).t, 1, 'closed segmentAt(length) t')

approx(closed.distance(7, 7), 0, 'closed distance on return segment')
const cn = closed.nearest(7, 7)
assert.equal(cn.index, 2, 'closed nearest(7,7) hits return segment')
approx(cn.t, 0.3, 'closed nearest(7,7) t')
arrEq(cn.point, [7, 0, 7], 'closed nearest(7,7) point')
approx(cn.distance, 0, 'closed nearest(7,7) distance')
approx(closed.distance(5, 3), Math.SQRT2, 'closed distance(5,3) to return segment')
const cn2 = closed.nearest(5, 3)
assert.equal(cn2.index, 2, 'closed nearest(5,3) hits return segment')
approx(cn2.t, 0.6, 'closed nearest(5,3) t')
arrEq(cn2.point, [4, 0, 4], 'closed nearest(5,3) point')
approx(cn2.distance, Math.SQRT2, 'closed nearest(5,3) distance')
assert.equal(closed.distance(5, 3, 1), Infinity, 'closed distance beyond within 1')
approx(closed.distance(5, 3, 2), Math.SQRT2, 'closed distance within 2')
assert.equal(closed.nearest(5, 3, 1), null, 'closed nearest beyond within 1')
assert.ok(closed.nearest(5, 3, 2) !== null, 'closed nearest within 2')

const planar = definePath([[0, 0], [10, 0], [10, 10]])
approx(planar.length, 20, '2D [x,z] points length')
arrEq(planar.at(0), [0, 0, 0], '2D point y defaults to 0')
const objPts = definePath([{ x: 0, z: 0 }, { x: 10, y: 2, z: 0 }, { x: 10, z: 10 }])
arrEq(objPts.at(1), [10, 2, 0], 'object points keep y')
approx(definePath([[0, 0], [10, 0], [10, 10]], { closed: true }).length, 20 + RETURN_LEN, 'closed 2D length')
approx(definePath(PTS, {}).length, 20, 'empty options keep open shape')
approx(definePath(PTS, { closed: false, smooth: false, spacing: 0 }).length, 20, 'explicit defaults keep open shape')

refuses(() => definePath([]), 'path-points-invalid')
refuses(() => definePath([P0]), 'path-points-invalid')
refuses(() => definePath('nope'), 'path-points-invalid')
refuses(() => definePath([P0, [NaN, 0, 0]]), 'path-point-invalid')
refuses(() => definePath([P0, 'x']), 'path-point-invalid')
refuses(() => definePath([P0, { x: 1 }]), 'path-point-invalid')
refuses(() => definePath(PTS, 5), 'path-options-invalid')
refuses(() => definePath(PTS, null), 'path-options-invalid')
refuses(() => definePath(PTS, [1]), 'path-options-invalid')
refuses(() => definePath(PTS, { closed: 'yes' }), 'path-closed-invalid')
refuses(() => definePath(PTS, { smooth: 1 }), 'path-smooth-invalid')
refuses(() => definePath(PTS, { spacing: -1 }), 'path-spacing-invalid')
refuses(() => definePath(PTS, { spacing: Infinity }), 'path-spacing-invalid')
refuses(() => definePath(PTS, { spacing: NaN }), 'path-spacing-invalid')
refuses(() => open.distance(NaN, 0), 'path-query-invalid')
refuses(() => open.nearest(0, 'z'), 'path-query-invalid')
refuses(() => open.distance(0, 0, -1), 'path-within-invalid')
refuses(() => open.nearest(0, 0, NaN), 'path-within-invalid')
refuses(() => open.at(0.5), 'path-index-invalid')
refuses(() => closed.at(NaN), 'path-index-invalid')

console.log(`RESULT: PASS open+closed 3-point paths, within/beyond cutoffs, wrap-around indices, ${MEMBERS.length} handle members, ${refusals} coded refusals`)
